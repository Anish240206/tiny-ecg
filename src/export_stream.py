"""Export a stretch of an MIT-BIH record as a C header for the ESP32-S3 sliding-window replay.

Mirrors src/stream_sim.py exactly (same preprocessing, windows, z-score, threshold, k-of-m rule),
and also stores the desktop INT8 results per window so the board can compare itself against them.

Place this file in src/ and run from the repo root (venv active):

    python -m src.export_stream --record 210 --preset balanced --start 0 --seconds 300

Writes firmware/sliding_window_loop/stream_data.h and copies models/ecg_ae_model.h next to it.
"""
import argparse
import shutil
from collections import deque
from pathlib import Path

import numpy as np

from . import config as C
from .dataset import load_record, preprocess
from .stream_sim import PRESETS, get_threshold
from .tflite_utils import TFLiteAE


def c_array(f, decl, vals, fmt, per_line=12):
    f.write(f"{decl} = {{\n")
    for i in range(0, len(vals), per_line):
        f.write("  " + ", ".join(fmt % v for v in vals[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--record", type=int, default=210)
    ap.add_argument("--preset", choices=PRESETS, default="balanced")
    ap.add_argument("--start", type=float, default=0, help="start offset in seconds")
    ap.add_argument("--seconds", type=float, default=300)
    ap.add_argument("--out", default=str(C.ROOT / "firmware" / "sliding_window_loop"))
    args = ap.parse_args()

    pct, k, m = PRESETS[args.preset]
    thr = get_threshold(pct, k, m)
    q = TFLiteAE(C.MODELS_DIR / "autoencoder_int8.tflite")

    sig, bs, sym = load_record(args.record)
    sig, bidx = preprocess(sig, bs)
    a = int(args.start * C.FS)
    sig = sig[a: a + int(args.seconds * C.FS)].astype(np.float32)
    bidx = bidx - a
    W, S = C.WINDOW, C.STRIDE_EVAL

    # reference run: same loop as stream_sim (evaluation at sample counts W, W+S, W+2S, ...)
    recent = deque(maxlen=m)
    ref_err, ref_flag, ref_alarm, truth = [], [], [], []
    prev, episodes = False, 0
    for end in range(W, len(sig) + 1, S):
        w = sig[end - W:end]
        w = ((w - w.mean()) / (w.std() + 1e-6))[:, None].astype(np.float32)
        e = float(q.error(w))
        flag = e > thr
        recent.append(flag)
        alarm = sum(recent) >= k
        in_win = sym[(bidx >= end - W) & (bidx < end)]
        truth.append(int(np.any(in_win != C.NORMAL_SYMBOL)))
        ref_err.append(e); ref_flag.append(int(flag)); ref_alarm.append(int(alarm))
        episodes += int(alarm and not prev); prev = alarm

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    path = out / "stream_data.h"
    with open(path, "w", newline="\n") as f:
        f.write("// Generated by src/export_stream.py - do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f'#define SW_RECORD {args.record}\n#define SW_PRESET "{args.preset}"\n')
        f.write(f"#define SW_START_S {args.start:.3f}f\n")
        f.write(f"#define SW_FS {C.FS}\n#define SW_WINDOW {W}\n#define SW_STRIDE {S}\n")
        f.write(f"#define SW_K {k}\n#define SW_M {m}\n#define SW_THRESHOLD {thr:.9g}f\n")
        f.write(f"#define SW_LEN {len(sig)}\n#define SW_NUM_WIN {len(ref_err)}\n")
        f.write(f"#define SW_REF_FLAGGED {sum(ref_flag)}\n#define SW_REF_ALARM_WINDOWS {sum(ref_alarm)}\n")
        f.write(f"#define SW_REF_EPISODES {episodes}\n#define SW_TRUTH_ANOM {sum(truth)}\n\n")
        c_array(f, "const float SW_STREAM[SW_LEN]", sig.tolist(), "%.9g")
        c_array(f, "const float SW_REF_ERR[SW_NUM_WIN]", ref_err, "%.9g")
        c_array(f, "const uint8_t SW_REF_FLAG[SW_NUM_WIN]", ref_flag, "%d", 40)
        c_array(f, "const uint8_t SW_REF_ALARM[SW_NUM_WIN]", ref_alarm, "%d", 40)
        c_array(f, "const uint8_t SW_TRUTH[SW_NUM_WIN]", truth, "%d", 40)

    model_h = C.MODELS_DIR / "ecg_ae_model.h"
    if model_h.exists():
        shutil.copy(model_h, out / "ecg_ae_model.h")
    else:
        print("WARNING: models/ecg_ae_model.h not found - copy it into the sketch folder by hand")

    print(f"wrote {path} ({path.stat().st_size / 1024:.0f} KB)")
    print(f"record {args.record} | preset {args.preset} (val p{pct}, {k}-of-{m}) | threshold {thr:.4f}")
    print(f"{len(sig)} samples | {len(ref_err)} windows | truth-anomalous {sum(truth)} | "
          f"flagged {sum(ref_flag)} | alarm windows {sum(ref_alarm)} | alarm episodes {episodes}")
    print("The board should report the same counts (a few flags near the threshold may differ).")


if __name__ == "__main__":
    main()
