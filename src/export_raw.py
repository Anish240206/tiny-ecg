"""Export raw 360 Hz MIT-BIH samples (as ADC counts) plus the band-pass filter coefficients,
so the ESP32-S3 can run the causal filter + decimation itself.

Place in src/ and run from the repo root (venv active), AFTER src.export_stream:

    python -m src.export_raw --record 210 --seconds 300

Writes firmware/sliding_window_loop/raw_data.h.
(Start is always 0: the causal filter is initialised on the first sample, exactly like src/dataset.py.)
"""
import argparse
from pathlib import Path

import numpy as np
import wfdb
from scipy.signal import butter, sosfilt, sosfilt_zi

from . import config as C
from .dataset import load_record, preprocess


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--record", type=int, default=210)
    ap.add_argument("--seconds", type=float, default=300)
    ap.add_argument("--out", default=str(C.ROOT / "firmware" / "sliding_window_loop"))
    args = ap.parse_args()
    if not C.CAUSAL:
        raise SystemExit("config.CAUSAL is False: the zero-phase filter cannot run on the board")

    rec = wfdb.rdrecord(str(C.DATA_DIR / str(args.record)), physical=False)
    ch = rec.sig_name.index("MLII")
    n = int(args.seconds * C.FS) * C.DECIM                 # raw samples -> exactly seconds*FS decimated samples
    raw = np.asarray(rec.d_signal[:n, ch], dtype=np.int64)
    gain = float(rec.adc_gain[ch])
    assert raw.min() >= -32768 and raw.max() <= 32767

    sos = butter(3, C.BAND, btype="band", fs=C.FS_RAW, output="sos")
    zi = sosfilt_zi(sos)

    # self-check: the exact recursion the board runs (transposed direct form II, state = zi * x0),
    # applied to the raw counts, must reproduce src/dataset.py's filtered stream
    x = raw.astype(np.float64)
    z = zi * x[0]
    y = np.empty_like(x)
    for i, xi in enumerate(x):
        for s in range(len(sos)):
            b0, b1, b2, _, a1, a2 = sos[s]
            o = b0 * xi + z[s, 0]
            z[s, 0] = b1 * xi - a1 * o + z[s, 1]
            z[s, 1] = b2 * xi - a2 * o
            xi = o
        y[i] = xi
    board = (y / gain)[::C.DECIM]
    sig, bs, _ = load_record(args.record)
    desk, _ = preprocess(sig, bs)
    desk = desk[:len(board)]
    err = np.abs(board - desk).max()
    print(f"python replica of the board filter vs src/dataset.py: max |diff| = {err:.3e} mV "
          f"(signal rms {desk.std():.3f} mV)")
    if err > 1e-3:
        raise SystemExit("filter replica does not match the desktop stream - do not flash")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    path = out / "raw_data.h"
    with open(path, "w", newline="\n") as f:
        f.write("// Generated by src/export_raw.py - do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define RAW_RECORD {args.record}\n#define RAW_FS {C.FS_RAW}\n#define RAW_DECIM {C.DECIM}\n")
        f.write(f"#define RAW_LEN {len(raw)}\n#define RAW_GAIN {gain:.9g}\n#define SOS_NSEC {len(sos)}\n\n")
        f.write("// per section: b0, b1, b2, a1, a2 (a0 = 1), transposed direct form II\n")
        f.write("const double SOS_COEF[SOS_NSEC][5] = {\n")
        for r in sos:
            f.write("  {" + ", ".join("%.17g" % v for v in (r[0], r[1], r[2], r[4], r[5])) + "},\n")
        f.write("};\n\nconst double SOS_ZI[SOS_NSEC][2] = {\n")
        for r in zi:
            f.write("  {" + ", ".join("%.17g" % v for v in r) + "},\n")
        f.write("};\n\nconst int16_t RAW_SAMPLES[RAW_LEN] = {\n")
        for i in range(0, len(raw), 20):
            f.write("  " + ", ".join(str(int(v)) for v in raw[i:i + 20]) + ",\n")
        f.write("};\n")
    print(f"wrote {path} ({path.stat().st_size / 1024:.0f} KB): {len(raw)} raw samples, "
          f"{len(sos)} filter sections, gain {gain:g} counts/mV")


if __name__ == "__main__":
    main()
